package com.example.db1jar;

import java.sql.Connection;
import java.sql.Statement;

import javax.sql.DataSource;

import org.apache.ibatis.session.SqlSessionFactory;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.mybatis.spring.annotation.MapperScan;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.boot.jdbc.DataSourceBuilder;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;

/**
 * 数据源 1 打在独立 jar 里。下面的方法参数不能改成
 * {@code @Qualifier("db1SqlSessionFactory")}，业务工程碰不到这些源码。
 * 按类型注入要保持唯一，第二个数据源必须 {@code autowireCandidate = false}。
 */
@Configuration
@MapperScan("com.example.db1jar")
public class Db1AutoConfiguration {

    static final String DDL = "CREATE TABLE IF NOT EXISTS note ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "body VARCHAR(255) NOT NULL)";

    @Bean
    @ConfigurationProperties("app.datasource.db1")
    public DataSource db1DataSource() {
        return DataSourceBuilder.create().build();
    }

    @Bean
    public SqlSessionFactory db1SqlSessionFactory(DataSource dataSource) throws Exception {
        SqlSessionFactoryBean factory = new SqlSessionFactoryBean();
        factory.setDataSource(dataSource);
        return factory.getObject();
    }

    @Bean
    public SqlSessionTemplate db1SqlSessionTemplate(SqlSessionFactory sqlSessionFactory) {
        return new SqlSessionTemplate(sqlSessionFactory);
    }

    @Bean
    public DataSourceTransactionManager db1TransactionManager(DataSource dataSource) {
        return new DataSourceTransactionManager(dataSource);
    }

    @Bean
    public Db1NoteService db1NoteService(Db1NoteMapper mapper) {
        return new Db1NoteService(mapper);
    }

    @Bean
    ApplicationRunner db1Schema(DataSource dataSource) {
        return args -> {
            try (Connection connection = dataSource.getConnection();
                    Statement statement = connection.createStatement()) {
                statement.execute(DDL);
            }
        };
    }
}
