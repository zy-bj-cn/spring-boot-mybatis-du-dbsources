package com.example.dudb.db2;

import java.sql.Connection;
import java.sql.Statement;

import javax.sql.DataSource;

import org.apache.ibatis.session.SqlSessionFactory;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.mybatis.spring.annotation.MapperScan;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.boot.jdbc.DataSourceBuilder;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;

/**
 * 数据源 2 全部 {@code autowireCandidate = false}。
 * jar 里的 {@code db1SqlSessionFactory(DataSource)} 没有 {@code @Qualifier}，
 * 按类型注入时就看不到这一组 bean，只会命中数据源 1。
 * 这里通过同一配置类的方法调用拿到数据源 2，不走按类型注入。
 */
@Configuration
@MapperScan(basePackages = "com.example.dudb.db2", sqlSessionTemplateRef = "db2SqlSessionTemplate")
public class Db2DataSourceConfig {

    static final String DDL = "CREATE TABLE IF NOT EXISTS note ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "body VARCHAR(255) NOT NULL)";

    @Bean(name = "db2DataSource", autowireCandidate = false)
    @ConfigurationProperties("app.datasource.db2")
    public DataSource db2DataSource() {
        return DataSourceBuilder.create().build();
    }

    @Bean(name = "db2SqlSessionFactory", autowireCandidate = false)
    public SqlSessionFactory db2SqlSessionFactory() throws Exception {
        SqlSessionFactoryBean factory = new SqlSessionFactoryBean();
        factory.setDataSource(db2DataSource());
        return factory.getObject();
    }

    @Bean(name = "db2SqlSessionTemplate", autowireCandidate = false)
    public SqlSessionTemplate db2SqlSessionTemplate() throws Exception {
        return new SqlSessionTemplate(db2SqlSessionFactory());
    }

    @Bean(name = "db2TransactionManager", autowireCandidate = false)
    public DataSourceTransactionManager db2TransactionManager() {
        return new DataSourceTransactionManager(db2DataSource());
    }

    @Bean
    ApplicationRunner db2Schema() {
        DataSource dataSource = db2DataSource();
        return args -> {
            try (Connection connection = dataSource.getConnection();
                    Statement statement = connection.createStatement()) {
                statement.execute(DDL);
            }
        };
    }
}
