package com.example.dudb;

import javax.sql.DataSource;

import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.ApplicationRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
public class SchemaInitializer {

    static final String DDL = "CREATE TABLE IF NOT EXISTS note ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "body VARCHAR(255) NOT NULL)";

    @Bean
    ApplicationRunner createNoteTables(
            @Qualifier("db1DataSource") DataSource db1,
            @Qualifier("db2DataSource") DataSource db2) {
        return args -> {
            DataSource[] sources = new DataSource[] { db1, db2 };
            for (DataSource dataSource : sources) {
                try (java.sql.Connection connection = dataSource.getConnection();
                        java.sql.Statement statement = connection.createStatement()) {
                    statement.execute(DDL);
                }
            }
        };
    }
}
